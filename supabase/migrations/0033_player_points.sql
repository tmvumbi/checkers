-- Global player points, separate from tournament-stage standings points.
-- Awards are written by database triggers and recorded in an immutable ledger
-- so retries can never credit the same result twice.

alter table public.profiles
  add column if not exists points bigint not null default 0;

create index if not exists profiles_points_rank_idx
  on public.profiles (points desc, rating desc)
  where nickname <> '' and points > 0;

create table if not exists public.point_awards (
  id bigint generated by default as identity primary key,
  uid uuid not null references public.profiles (id) on delete cascade,
  award_type text not null check (award_type in ('pc_win', 'tournament_win')),
  source_id uuid not null,
  points int not null check (points > 0),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (award_type, source_id, uid)
);

alter table public.point_awards enable row level security;
revoke all on public.point_awards from public, anon, authenticated;

-- Existing values win when this migration is re-applied.
update public.app_config
set config = jsonb_set(
  config,
  '{points}',
  jsonb_build_object(
    'pc_easy_win', 1,
    'pc_medium_win', 5,
    'pc_hard_win', 10,
    'tournament_per_participant', 1,
    'tournament_bonus', 0
  ) || coalesce(config -> 'points', '{}'::jsonb),
  true
)
where id = 'public';

create or replace function public._point_rule_int(
  p_key text,
  p_default int
) returns int
language plpgsql stable security definer set search_path = public as $$
declare
  v_raw text;
begin
  select config #>> array['points', p_key]
    into v_raw
    from app_config
    where id = 'public';
  if v_raw is null or v_raw !~ '^[0-9]+$' then
    return p_default;
  end if;
  return least(v_raw::int, 1000000);
exception when numeric_value_out_of_range then
  return p_default;
end;
$$;

create or replace function public._record_point_award(
  p_uid uuid,
  p_award_type text,
  p_source_id uuid,
  p_points int,
  p_metadata jsonb default '{}'::jsonb
) returns boolean
language plpgsql security definer set search_path = public as $$
declare
  v_inserted_uid uuid;
begin
  if p_uid is null or p_points <= 0 then
    return false;
  end if;

  insert into point_awards (uid, award_type, source_id, points, metadata)
  values (p_uid, p_award_type, p_source_id, p_points,
          coalesce(p_metadata, '{}'::jsonb))
  on conflict (award_type, source_id, uid) do nothing
  returning uid into v_inserted_uid;

  if v_inserted_uid is null then
    return false;
  end if;

  update profiles set points = points + p_points where id = p_uid;
  return true;
end;
$$;

create or replace function public._award_pc_win_points()
returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_points int;
begin
  if not new.vs_pc
      or new.status <> 'finished'
      or old.status = 'finished'
      or new.winner_uid is null then
    return new;
  end if;

  v_points := case new.ai_level
    when 'easy' then _point_rule_int('pc_easy_win', 1)
    when 'medium' then _point_rule_int('pc_medium_win', 5)
    when 'hard' then _point_rule_int('pc_hard_win', 10)
    else 0
  end;

  perform _record_point_award(
    new.winner_uid,
    'pc_win',
    new.id,
    v_points,
    jsonb_build_object('ai_level', new.ai_level)
  );
  return new;
end;
$$;

drop trigger if exists award_pc_win_points on public.games;
create trigger award_pc_win_points
after update of status on public.games
for each row execute function public._award_pc_win_points();

create or replace function public._award_tournament_win_points()
returns trigger
language plpgsql security definer set search_path = public as $$
declare
  v_per_participant int;
  v_bonus int;
  v_points int;
begin
  if new.status <> 'finished'
      or old.status = 'finished'
      or new.winner_uid is null then
    return new;
  end if;

  v_per_participant := _point_rule_int('tournament_per_participant', 1);
  v_bonus := _point_rule_int('tournament_bonus', 0);
  v_points := greatest(0, new.participant_count * v_per_participant + v_bonus);

  perform _record_point_award(
    new.winner_uid,
    'tournament_win',
    new.id,
    v_points,
    jsonb_build_object(
      'participant_count', new.participant_count,
      'per_participant', v_per_participant,
      'bonus', v_bonus
    )
  );
  return new;
end;
$$;

drop trigger if exists award_tournament_win_points on public.tournaments;
create trigger award_tournament_win_points
after update of status on public.tournaments
for each row execute function public._award_tournament_win_points();

create or replace function public.get_points_leaderboard()
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_rows jsonb;
begin
  select coalesce(jsonb_agg(row_data order by points desc, rating desc),
                  '[]'::jsonb)
    into v_rows
    from (
      select jsonb_build_object(
        'uid', id,
        'nickname', nickname,
        'photo_url', photo_url,
        'rating', rating,
        'points', points,
        'rated_games', rated_games,
        'wins', wins,
        'losses', losses,
        'draws', draws
      ) as row_data, points, rating
      from profiles
      where points > 0 and nickname <> ''
      order by points desc, rating desc, created_at asc
      limit 30
    ) ranked;

  return v_rows;
end;
$$;

create or replace function public.get_point_rules()
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'pc_easy_win', _point_rule_int('pc_easy_win', 1),
    'pc_medium_win', _point_rule_int('pc_medium_win', 5),
    'pc_hard_win', _point_rule_int('pc_hard_win', 10),
    'tournament_per_participant',
      _point_rule_int('tournament_per_participant', 1),
    'tournament_bonus', _point_rule_int('tournament_bonus', 0)
  );
$$;

